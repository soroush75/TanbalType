# -*- coding: utf-8 -*-
"""
لغت‌نامهٔ فارسی برنامه را از big.txt می‌سازد و پاک‌سازی می‌کند.

خروجی PersianWords.txt است که به‌صورت EmbeddedResource داخل برنامه قرار می‌گیرد.

مراحل پاک‌سازی:
  ۱) نرمال‌سازی به فارسیِ استاندارد: تبدیل حروف عربی (ك→ک، ي/ى→ی، ة→ه، ...)،
     حذف اعراب و همزهٔ ترکیبی و کاراکترهای کنترلی (ZWJ، BOM، کشیده).
  ۲) حذف توکن‌های نامعتبر: کوتاه‌تر از ۲ حرف، بلندتر از ۱۳ حرف (کلمات به‌هم‌چسبیده)،
     یا دارای کاراکتر غیرفارسی.
  ۳) حذف چند واژهٔ بی‌معنی که با کلمات پرکاربرد انگلیسی تداخل دارند و مانع اصلاح می‌شوند.
  ۴) حذف ۷۵ کلمهٔ ۲-۳ حرفیِ بی‌معنی که با جستجوی زندهٔ آبادیس تأیید شدند.
  ۵) حذف توکن‌هایی که الگوی املایی‌شان در فارسی ممکن نیست (تکرار حرف، همزهٔ آغازین).
"""
import re

BIG_TXT = 'big.txt'
OUT = 'PersianWords.txt'

PERSIAN = set("ابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهیآئءؤ")
ZWNJ = '‌'

# اعراب/تنوین/همزهٔ ترکیبی/الف کوچک/کشیده + ZWJ + BOM  → حذف
_STRIP = dict.fromkeys(
    [0x064B, 0x064C, 0x064D, 0x064E, 0x064F, 0x0650, 0x0651, 0x0652,
     0x0653, 0x0654, 0x0655, 0x0670, 0x0640, 0x200D, 0xFEFF], None)

# واژه‌های بی‌معنی که تصویرِ کلیدهای فارسیِ یک کلمهٔ پرکاربرد انگلیسی‌اند
# (نگه‌داشتنشان مانع اصلاح آن کلمهٔ انگلیسی می‌شد؛ خودشان کلمهٔ فارسی واقعی نیستند)
COLLISION_JUNK = {
    # مجموعهٔ اولیه
    "زشد", "یهی", "تعسف", "مخشی",
    # موارد درخواستی کاربر (دنباله‌های کوتاه/بی‌معنی که مانع انگلیسی پرکاربرد بودند)
    "شس", "شف", "زخ", "اث", "اشی", "اخص", "هب", "همم", "هد", "هق",
    "هس", "هف", "هفس", "هین", "تشد", "لل", "لهب", "لهف", "لد", "لخ",
    "دشا", "خن", "خد", "خق", "خس", "حز", "حیب", "ساث", "سخ", "فذا",
    "فاط", "فخ", "فغ", "عه", "عس", "عط", "صاغ", "صح",
    # موارد پسوندی (خودشان بی‌معنی‌اند؛ ولی مسدودکنندهٔ واقعی ممکن است ریشه باشد)
    "شذته", "اشاش", "تشرش", "نهدیش", "نختش", "رخهی", "بهدی",
}

# کلمات ۲-۳ حرفیِ بی‌معنی که با جستجوی زندهٔ آبادیس (abadis.ir/fatofa) تأیید شدند
# «پیدا نشد» — یعنی هیچ معنایی در دیکشنری/دانشنامهٔ فارسی ندارند (نویز/خطای منبع big.txt)
ABADIS_NOT_FOUND = {
    "ءای", "ءمی", "آاس", "آاق", "آال", "آثا", "آخز", "آذز", "آرر", "آغه",
    "آقو", "آهگ", "ئرت", "ئه", "خزت", "خزد", "خسس", "خسش", "خصو", "خطت",
    "خطش", "خطص", "خظر", "خفظ", "خقا", "خقن", "خقه", "خما", "خمم", "خنح",
    "خنص", "خنم", "خهک", "خوو", "خپر", "دئ", "دئر", "دئه", "دتن", "دتو",
    "ددث", "ددش", "دذ", "دذو", "دزش", "دزع", "دزو", "دشب", "دشل", "دشی",
    "دصد", "دفت", "دفش", "دفم", "دنچ", "دهت", "دهذ", "دپه", "دپچ", "دژا",
    "دژش", "دیچ", "ذبت", "ذغت", "ذلب", "ذلش", "ذوت", "ذوه", "ذیر", "رئت",
    "رخط", "ضیث", "طوز", "ظزف", "ظلک",
}

# واژه‌های بی‌معنی که با نام سایت‌های متداول تداخل داشتند و باعث می‌شدند
# نام سایت روی حالت انگلیسی اشتباهاً به فارسی تبدیل شود.
# «قشت/شعیه/شررش» با آبادیس تأیید شدند («پیدا نشد»)؛ «اا/زز/ائ» تکرارِ بی‌معنی حرف‌اند.
SITE_COLLISION_JUNK = {
    "اا", "زز", "ائ",        # hh, cc, hm
    "قشت", "شعیه", "شررش",   # raja, audi, avval
    "بشب",                   # fafa → «بشب»+«ش» (با آبادیس تأیید شد: بی‌معنی)
}


def normalize(w):
    w = (w.replace('ك', 'ک').replace('ي', 'ی').replace('ى', 'ی')
          .replace('ٱ', 'ا').replace('أ', 'ا').replace('إ', 'ا')
          .replace('ة', 'ه').replace('‐', '').replace('-', ''))
    return w.translate(_STRIP)


def valid(w):
    return 2 <= len(w) < 14 and all(ch in PERSIAN or ch == ZWNJ for ch in w)


def orthographic_junk(w):
    """الگوهایی که در خطِ فارسی ممکن نیستند — یعنی توکن قطعاً غلط یا بی‌معنی است."""
    if len(set(w)) == 1:
        return True                      # کل کلمه تکرار یک حرف است: «آآ»، «سسس»
    if re.search(r'(.)\1\1', w):
        return True                      # سه حرف یکسان پیاپی: «بخششش»، «برررسی»
    if w[0] in 'ءئ':
        return True                      # هیچ واژهٔ فارسی با همزهٔ تنها آغاز نمی‌شود
    return False


words = set()
with open(BIG_TXT, encoding='utf-8') as f:
    for line in f:
        for tok in re.split(r'[ ‌\t\n]+', line.strip()):
            n = normalize(tok.strip())
            if (valid(n) and not orthographic_junk(n) and n not in COLLISION_JUNK
                    and n not in ABADIS_NOT_FOUND and n not in SITE_COLLISION_JUNK):
                words.add(n)

sorted_words = sorted(words)
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(sorted_words))
    f.write('\n')

print(f"انجام شد: {len(sorted_words)} لغت یکتای پاک‌سازی‌شده در {OUT} نوشته شد.")
